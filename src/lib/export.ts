import { Platform } from 'react-native';
import { longDate, money, num } from './format';
import type { DotFile, FleetReport, Invoice, InvoiceLine, Organization } from './types';

const esc = (x: unknown) => String(x ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

const page = (title: string, body: string) => `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
  body{font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;color:#111;margin:32px;font-size:12px}
  h1{font-size:22px;margin:0 0 4px} h2{font-size:15px;margin:22px 0 6px;border-bottom:1px solid #ccc;padding-bottom:4px}
  .muted{color:#666} table{width:100%;border-collapse:collapse;margin-top:6px}
  th,td{text-align:left;padding:5px 6px;border-bottom:1px solid #e3e3e3;vertical-align:top} th{background:#f4f4f4}
  td.n,th.n{text-align:right} .tot td{font-weight:700;border-top:2px solid #333}
  .brand{display:flex;justify-content:space-between;align-items:flex-start;margin-bottom:12px}
</style></head><body>${body}
<p class="muted" style="margin-top:28px">Generated by Northgate Fleet Systems · ${esc(longDate(new Date().toISOString()))}</p></body></html>`;

const table = (head: string[], rows: (string | number)[][], numeric: number[] = [], foot?: (string | number)[]) =>
  `<table><thead><tr>${head.map((h, i) => `<th class="${numeric.includes(i) ? 'n' : ''}">${esc(h)}</th>`).join('')}</tr></thead><tbody>
  ${rows.map((r) => `<tr>${r.map((c, i) => `<td class="${numeric.includes(i) ? 'n' : ''}">${esc(c)}</td>`).join('')}</tr>`).join('')}
  ${foot ? `<tr class="tot">${foot.map((c, i) => `<td class="${numeric.includes(i) ? 'n' : ''}">${esc(c)}</td>`).join('')}</tr>` : ''}
  </tbody></table>`;

/** Print / save as PDF. Web opens the browser print dialog (Save as PDF); native shares a PDF file. */
export async function exportPdf(title: string, html: string) {
  if (Platform.OS === 'web') {
    const w = window.open('', '_blank');
    if (!w) throw new Error('Allow pop-ups to export');
    w.document.write(html);
    w.document.close();
    w.focus();
    setTimeout(() => w.print(), 250);
    return;
  }
  const { uri } = await Print.printToFileAsync({ html });
  await Sharing.shareAsync(uri, { mimeType: 'application/pdf', dialogTitle: title, UTI: 'com.adobe.pdf' });
}

export function toCsv(rows: (string | number | null | undefined)[][]): string {
  return rows.map((r) => r.map((c) => {
    const v = String(c ?? '');
    return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
  }).join(',')).join('\n');
}

export async function exportCsv(filename: string, rows: (string | number | null | undefined)[][]) {
  const csv = toCsv(rows);
  if (Platform.OS === 'web') {
    const url = URL.createObjectURL(new Blob([csv], { type: 'text/csv' }));
    const a = document.createElement('a');
    a.href = url; a.download = filename; a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    return;
  }
  const f = new File(Paths.cache, filename);
  if (f.exists) f.delete();
  f.create();
  f.write(csv);
  await Sharing.shareAsync(f.uri, { mimeType: 'text/csv', dialogTitle: filename });
}

