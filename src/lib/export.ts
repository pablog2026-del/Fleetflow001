const orgHead = (org: Organization, title: string, sub: string) => `
  <div class="brand"><div><h1>${esc(title)}</h1><div class="muted">${esc(sub)}</div></div>
  <div style="text-align:right"><b>${esc(org.name)}</b>${org.account_number ? `<br>Account ${esc(org.account_number)}` : ''}
  <br>${esc([org.address_line1, org.city, org.state].filter(Boolean).join(', '))}${org.usdot_number ? `<br>USDOT ${esc(org.usdot_number)}` : ''}</div></div>`;

export function statementHtml(org: Organization, invoices: Invoice[]) {
  const open = invoices.filter((i) => i.status === 'open' || i.status === 'processing');
  const rows = invoices.filter((i) => i.status !== 'void')
    .map((i) => [i.number, longDate(i.issued_on), longDate(i.due_on), i.memo ?? '', i.status, money(i.total)]);
  return page('Statement', `${orgHead(org, 'Statement of account', `As of ${longDate(new Date().toISOString())}`)}
    <h2>Invoices</h2>${table(['Invoice', 'Issued', 'Due', 'Description', 'Status', 'Amount'], rows, [5],
      ['', '', '', '', 'Balance due', money(open.reduce((s, i) => s + Number(i.total), 0))])}
    <p class="muted">Labor billed at OEM book time × rate. Parts billed at cost. Sales tax per NC rules (confirmed by CPA).</p>`);
}

export function yearEndHtml(org: Organization, year: number, invoices: Invoice[], lines: InvoiceLine[], units: Record<string, string>) {
  const inYear = invoices.filter((i) => i.status !== 'void' && i.issued_on.startsWith(String(year)));
  const ids = new Set(inYear.map((i) => i.id));
  const ls = lines.filter((l) => ids.has(l.invoice_id));
  const byType = (t: string) => ls.filter((l) => l.line_type === t).reduce((s, l) => s + Number(l.amount), 0);
  const byUnit: Record<string, number> = {};
  for (const l of ls) { const u = l.vehicle_id ? units[l.vehicle_id] ?? '—' : 'Plan / fleet-wide'; byUnit[u] = (byUnit[u] ?? 0) + Number(l.amount); }
  const paid = inYear.filter((i) => i.status === 'paid').reduce((s, i) => s + Number(i.total), 0);
  return page(`Year-end ${year}`, `${orgHead(org, `Year-end summary · ${year}`, 'For your accountant')}
    <h2>Totals</h2>${table(['Category', 'Amount'], [
      ['Labor', money(byType('labor'))], ['Parts (at cost)', money(byType('part'))], ['Plan fees', money(byType('fee'))],
      ['Sublet', money(byType('sublet'))], ['Sales tax', money(inYear.reduce((s, i) => s + Number(i.tax), 0))],
    ], [1], ['Total billed', money(inYear.reduce((s, i) => s + Number(i.total), 0))])}
    <p>Paid in ${year}: <b>${money(paid)}</b></p>
    <h2>By truck</h2>${table(['Unit', 'Amount'], Object.entries(byUnit).sort().map(([u, a]) => [u, money(a)]), [1])}
    <h2>Invoices</h2>${table(['Invoice', 'Issued', 'Description', 'Status', 'Amount'],
      inYear.map((i) => [i.number, longDate(i.issued_on), i.memo ?? '', i.status, money(i.total)]), [4])}`);
}

export function fleetReportHtml(org: Organization, r: FleetReport) {
  const pct = (a: number, b: number) => (b ? `${Math.round((a / b) * 100)}%` : '—');
  return page('Fleet report', `${orgHead(org, 'Fleet report', `${longDate(r.from)} – ${longDate(r.to)}`)}
    <h2>By truck</h2>${table(['Unit', 'Truck', 'Miles', 'Eng hrs', 'Spend', '$/mi', '$/eng hr', 'Downtime days', 'PM on time', 'Overdue now'],
      r.trucks.map((t) => [t.unit, [t.year, t.make, t.model].filter(Boolean).join(' '), num(t.miles), num(t.hours), money(t.spend),
        t.cost_per_mile != null ? `$${Number(t.cost_per_mile).toFixed(3)}` : '—', t.cost_per_hour != null ? money(t.cost_per_hour) : '—',
        t.downtime_days, `${t.pm_on_time}/${t.pm_done}`, t.pm_overdue_now]), [2, 3, 4, 5, 6, 7, 9])}
    <h2>Spend by category</h2>${table(['Category', 'Amount'], Object.entries(r.by_category).map(([k, v]) => [categoryLabel(k), money(v)]), [1],
      ['Total', money(r.totals.spend)])}
    <h2>PM compliance</h2><p>${r.totals.pm_on_time} of ${r.totals.pm_done} PMs done on time (${pct(r.totals.pm_on_time, r.totals.pm_done)}) · ${r.totals.pm_overdue_now} items overdue now · ${r.totals.downtime_days} downtime days.</p>`);
}

export function fleetReportCsv(r: FleetReport): (string | number | null)[][] {
  return [
    ['Unit', 'Year', 'Make', 'Model', 'Miles', 'Engine hours', 'Spend', 'Cost per mile', 'Cost per engine hour', 'Downtime days', 'PM done', 'PM on time', 'Overdue now'],
    ...r.trucks.map((t) => [t.unit, t.year, t.make, t.model, t.miles, t.hours, t.spend, t.cost_per_mile, t.cost_per_hour, t.downtime_days, t.pm_done, t.pm_on_time, t.pm_overdue_now]),
    [],
    ['Category', 'Spend'],
    ...Object.entries(r.by_category).map(([k, v]) => [categoryLabel(k), v]),
  ];
}

export function dotFileHtml(d: DotFile) {
  const v = d.vehicle;
  return page(`DOT file · Unit ${v.unit}`, `
    <div class="brand"><div><h1>DOT file · Unit ${esc(v.unit)}</h1><div class="muted">${esc([v.year, v.make, v.model].filter(Boolean).join(' '))} · VIN ${esc(v.vin)}</div></div>
    <div style="text-align:right"><b>${esc(d.carrier.name)}</b>${d.carrier.usdot ? `<br>USDOT ${esc(d.carrier.usdot)}` : ''}<br>${esc(d.carrier.address)}</div></div>
    ${table(['Plate', 'Odometer', 'Engine hours'], [[`${v.plate ?? '—'} ${v.plate_state ?? ''}`, num(v.odometer), num(v.engine_hours)]])}
    <h2>Annual inspection (49 CFR 396.17)</h2>
    ${d.annual_inspection ? table(['RA', 'Date', 'Miles', 'Next due'], [[`#${d.annual_inspection.id}`, longDate(d.annual_inspection.date), num(d.annual_inspection.miles), longDate(d.annual_inspection.next_due)]])
      : '<p><b>No annual inspection on file.</b></p>'}
    <h2>Defects reported &amp; closed</h2>
    ${d.defects_closed.length ? table(['RA', 'Reported', 'Closed', 'Defect'], d.defects_closed.map((x) => [`#${x.id}`, longDate(x.reported), longDate(x.closed), `${x.title}${x.description ? ' — ' + x.description : ''}`])) : '<p class="muted">None.</p>'}
    <h2>Deferred by owner</h2>
    ${d.deferred.length ? table(['RA', 'Date', 'Item', 'Reason', 'Until'], d.deferred.map((x) => [`#${x.id}`, longDate(x.date), x.title, x.reason, x.until ? longDate(x.until) : '—'])) : '<p class="muted">None.</p>'}
    <h2>Open items</h2>
    ${d.open_items.length ? table(['RA', 'Opened', 'Item', 'Status'], d.open_items.map((x) => [`#${x.id}`, longDate(x.opened), x.title, x.status])) : '<p class="muted">None.</p>'}
    <h2>Repair &amp; maintenance history</h2>
    ${d.repair_history.length ? table(['RA', 'Date', 'Work', 'Component', 'Miles', 'Amount'], d.repair_history.map((x) => [`#${x.id}`, longDate(x.date), x.title, x.component, num(x.miles), money(x.total)]), [4, 5]) : '<p class="muted">None.</p>'}`);
}

export function serviceReportHtml(o: { fleet: string; unit: string; vin: string; id: number; title: string; completed: string | null;
  miles: number | null; lines: { description: string; amount: number }[]; events: { text: string; created_at: string }[] }) {
  return page(`Service report RA #${o.id}`, `<h1>Service report · RA #${o.id}</h1>
    <div class="muted">${esc(o.fleet)} · Unit ${esc(o.unit)} · VIN ${esc(o.vin)}</div>
    <p><b>${esc(o.title)}</b><br>Completed ${esc(longDate(o.completed))}${o.miles ? ` at ${num(o.miles)} mi` : ''}</p>
    <h2>Work &amp; cost</h2>${table(['Line', 'Amount'], o.lines.map((l) => [l.description, money(l.amount)]), [1],
      ['Total', money(o.lines.reduce((s, l) => s + Number(l.amount), 0))])}
    <p class="muted">Labor from the OEM book-time guide. Parts billed at cost — no markup.</p>
    <h2>Timeline</h2>${table(['When', 'Event'], o.events.map((e) => [new Date(e.created_at).toLocaleString('en-US'), e.text]))}`);
}

export const categoryLabel = (k: string) =>
  ({ pm: 'Preventive maintenance', repair: 'Repair', tires: 'Tires', breakdown: 'Breakdown', inspection: 'Inspection', plan: 'Monthly plan' } as Record<string, string>)[k] ?? k;
