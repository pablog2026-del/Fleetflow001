create or replace function pg_temp.items(p_type text, p_rows jsonb) returns void language plpgsql as $$
declare r jsonb; v_section text := null; v_sp int := 0; v_p int := 0;
begin
  for r in select * from jsonb_array_elements(p_rows) loop
    if r->>0 is distinct from v_section then v_section := r->>0; v_sp := v_sp + 1; v_p := 0; end if;
    v_p := v_p + 1;
    insert into public.inspection_items (type_key, section, section_position, position, label, guidance, reference, measure_unit, critical)
    values (p_type, v_section, v_sp, v_p, r->>1, r->>2, r->>3, r->>4, coalesce((r->>5)::boolean, false));
  end loop;
end $$;

