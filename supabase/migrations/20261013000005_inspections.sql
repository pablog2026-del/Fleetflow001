-- ---------------------------------------------------------------- activity hooks
-- An activity created from an inspection interval, or requested as an inspection, carries the type.
create or replace function public._activity_inspection_type()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.inspection_type_key is null and new.interval_id is not null then
    select inspection_type_key into new.inspection_type_key from service_intervals where id = new.interval_id;
  end if;
  if new.inspection_type_key is null and new.kind = 'request' then
    new.inspection_type_key := case new.title when 'DOT inspection' then 'annual'
                                              when 'Vehicle inspection' then 'annual'
                                              when 'Monthly inspection' then 'monthly' end;
  end if;
  if new.inspection_type_key is not null then new.category := 'inspection'; end if;
  return new;
end $$;
create trigger activity_inspection_type before insert on public.repair_activities
  for each row execute function public._activity_inspection_type();

-- An inspection activity can only be completed by completing its checklist.
create or replace function public._inspection_must_be_done()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'done' and old.status <> 'done' and new.inspection_type_key is not null
     and not exists (select 1 from inspections where activity_id = new.id and status = 'completed') then
    raise exception 'complete the inspection checklist first' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger activity_inspection_done before update on public.repair_activities
  for each row execute function public._inspection_must_be_done();

-- Out-of-service defects keep the truck down until they are repaired.
create or replace function public._back_in_service(p_vehicle uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from repair_activities a
             where a.vehicle_id = p_vehicle and a.status = 'progress') then return; end if;
  if exists (select 1 from repair_activities a
             where a.vehicle_id = p_vehicle and (a.kind = 'breakdown' or a.urgency = 'Out of service')
               and a.status in ('requested', 'estimate', 'scheduled', 'deferred')) then return; end if;
  update vehicles set in_service = true where id = p_vehicle;
  update vehicle_downtime set ended_at = now() where vehicle_id = p_vehicle and ended_at is null;
end $$;

-- ---------------------------------------------------------------- RPCs
-- Provider (Admin in stage one) opens the checklist for an inspection activity.
create or replace function public.start_inspection(p_activity bigint)
returns bigint language plpgsql security definer set search_path = public as $$
declare a repair_activities; v vehicles; v_id bigint;
begin
  select * into a from repair_activities where id = p_activity;
  perform _require(can_work_fleet(a.fleet_org_id), 'provider only');
  perform _require(a.inspection_type_key is not null, 'this repair activity is not an inspection');
  select id into v_id from inspections where activity_id = p_activity and status = 'in_progress';
  if v_id is not null then return v_id; end if;
  perform _require(a.status in ('scheduled', 'progress'), 'the inspection has to be approved and scheduled first');
  if a.status = 'scheduled' then perform start_work(p_activity); end if;
  select * into v from vehicles where id = a.vehicle_id;
  insert into inspections (type_key, fleet_org_id, vehicle_id, activity_id, odometer_miles, engine_hours, inspector_id, inspector_name)
  values (a.inspection_type_key, a.fleet_org_id, a.vehicle_id, a.id, v.odometer_miles, v.engine_hours, auth.uid(),
          (select full_name from profiles where id = auth.uid()))
  returning id into v_id;
  perform _add_event(p_activity, 'Inspection #' || v_id || ' started');
  return v_id;
end $$;

create or replace function public.record_inspection_item(p_inspection bigint, p_item uuid, p_result public.inspection_result,
                                                         p_measurement text default null, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
declare i inspections; it inspection_items;
begin
  select * into i from inspections where id = p_inspection;
  perform _require(can_work_fleet(i.fleet_org_id), 'provider only');
  perform _require(i.status = 'in_progress', 'this inspection is already completed');
  select * into it from inspection_items where id = p_item;
  perform _require(it.type_key = i.type_key, 'item is not on this checklist');
  perform _require(p_result <> 'fail' or coalesce(trim(p_note), '') <> '', 'describe the defect');
  insert into inspection_results (inspection_id, item_id, result, measurement, note, recorded_by)
  values (p_inspection, p_item, p_result, nullif(trim(p_measurement), ''), nullif(trim(p_note), ''), auth.uid())
  on conflict (inspection_id, item_id) do update set result = excluded.result, measurement = excluded.measurement,
    note = excluded.note, recorded_by = excluded.recorded_by, recorded_at = now();
end $$;

-- Finish the checklist: completes (and invoices) the inspection activity, and opens a
-- defects repair activity for anything that failed. Critical failures take the truck out of service.
create or replace function public.complete_inspection(p_inspection bigint, p_miles numeric default null, p_hours numeric default null,
                                                      p_inspector text default null, p_notes text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare i inspections; v vehicles; t inspection_types; v_missing int; v_unmeasured int; v_fails text;
        v_critical boolean; v_passed boolean; v_defects bigint;
begin
  select * into i from inspections where id = p_inspection;
  perform _require(can_work_fleet(i.fleet_org_id), 'provider only');
  perform _require(i.status = 'in_progress', 'this inspection is already completed');
  select * into t from inspection_types where key = i.type_key;

  select count(*) into v_missing from inspection_items it
  where it.type_key = i.type_key and it.active
    and not exists (select 1 from inspection_results r where r.inspection_id = i.id and r.item_id = it.id);
  perform _require(v_missing = 0, v_missing || ' checklist item(s) still need a result');
  select count(*) into v_unmeasured from inspection_results r join inspection_items it on it.id = r.item_id
  where r.inspection_id = i.id and it.measure_unit is not null and r.result in ('pass', 'fail') and r.measurement is null;
  perform _require(v_unmeasured = 0, v_unmeasured || ' reading(s) still need a measurement');

  select string_agg('• ' || it.section || ': ' || it.label || coalesce(' — ' || r.note, ''), E'\n' order by it.section_position, it.position),
         coalesce(bool_or(it.critical), false)
    into v_fails, v_critical
  from inspection_results r join inspection_items it on it.id = r.item_id
  where r.inspection_id = i.id and r.result = 'fail';
  v_passed := v_fails is null;

  select * into v from vehicles where id = i.vehicle_id;
  update inspections set status = 'completed', completed_at = now(), passed = v_passed,
    odometer_miles = greatest(coalesce(p_miles, v.odometer_miles), v.odometer_miles),
    engine_hours = greatest(coalesce(p_hours, v.engine_hours), v.engine_hours),
    inspector_name = coalesce(nullif(trim(p_inspector), ''), inspector_name), notes = nullif(trim(p_notes), '')
  where id = i.id;

  perform _add_event(i.activity_id, 'Inspection #' || i.id || case when v_passed then ' passed' else ' found defects' end);
  perform complete_activity(i.activity_id, p_miles, p_hours,
    t.name || ' #' || i.id || case when v_passed then ' · passed' else ' · defects found' end);

  if not v_passed then
    v_defects := _new_activity(v.id, 'request', 'repair', 'requested', 'Defects from ' || lower(t.name) || ' #' || i.id,
                               'General', v_fails, case when v_critical then 'Out of service' else 'This week' end);
    -- defect repairs are ordinary repairs, not another inspection
    update repair_activities set inspection_type_key = null, category = 'repair' where id = v_defects;
    update inspections set defects_activity_id = v_defects where id = i.id;
    perform _add_event(v_defects, 'Opened from inspection #' || i.id);
    if v_critical then
      perform _out_of_service(v.id, v_defects);
      perform _add_event(v_defects, 'Out-of-service defect: truck stays down until repaired');
    end if;
    perform _notify_org(i.fleet_org_id, 'Inspection found defects · Unit ' || v.unit_number,
      case when v_critical then 'Out of service until repaired. ' else '' end || 'An estimate follows for your approval.',
      v_critical, v_defects);
    perform _notify_provider(v_defects, 'Defects to estimate · Unit ' || v.unit_number, v_fails, v_critical);
  else
    perform _notify_org(i.fleet_org_id, t.name || ' passed · Unit ' || v.unit_number, null, false, i.activity_id);
  end if;
  return jsonb_build_object('passed', v_passed, 'defects_activity_id', v_defects, 'out_of_service', coalesce(v_critical, false));
end $$;

