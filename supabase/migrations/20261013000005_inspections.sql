-- Inspections with checklists.
--   annual  · Vehicle inspection — periodic inspection required at least every 12 months
--             (49 CFR 396.17), checklist follows the minimum standards in Appendix G to Part 396.
--   monthly · Monthly in-depth inspection — Northgate / PG Heavy Duty shop standard for
--             heavy-duty dump trucks, every 30 days.
-- Checklists are data (inspection_types + inspection_items), so more types can be added
-- without code. An inspection is performed inside a repair activity, so it is scheduled,
-- approved and invoiced like any other work; failed items open a defects repair activity
-- that the owner approves before repair.

create type public.inspection_result as enum ('pass', 'fail', 'repaired', 'na');

create table public.inspection_types (
  key text primary key,
  name text not null,
  description text,
  every_days int,
  regulation text,
  position int not null default 0
);

create table public.inspection_items (
  id uuid primary key default gen_random_uuid(),
  type_key text not null references public.inspection_types(key) on delete cascade,
  section text not null,
  section_position int not null,
  position int not null,
  label text not null,
  guidance text,
  reference text,
  measure_unit text,        -- when set, a reading is recorded (psi, in, 32nds, V, sec ...)
  critical boolean not null default false,  -- a failure puts the truck out of service until repaired
  active boolean not null default true,
  unique (type_key, section_position, position)
);

create table public.inspections (
  id bigint generated by default as identity (start with 2001) primary key,
  type_key text not null references public.inspection_types(key),
  fleet_org_id uuid not null references public.organizations(id) on delete cascade,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  activity_id bigint references public.repair_activities(id) on delete set null,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  passed boolean,
  odometer_miles numeric(12,1),
  engine_hours numeric(12,1),
  inspector_id uuid references auth.users(id),
  inspector_name text,
  notes text,
  defects_activity_id bigint references public.repair_activities(id) on delete set null,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);
create index on public.inspections (vehicle_id, completed_at desc);
create unique index inspections_one_open_per_activity on public.inspections (activity_id) where status = 'in_progress';

create table public.inspection_results (
  inspection_id bigint not null references public.inspections(id) on delete cascade,
  item_id uuid not null references public.inspection_items(id),
  result public.inspection_result not null,
  measurement text,
  note text,
  recorded_by uuid references auth.users(id),
  recorded_at timestamptz not null default now(),
  primary key (inspection_id, item_id)
);

alter table public.interval_templates add column inspection_type_key text references public.inspection_types(key);
